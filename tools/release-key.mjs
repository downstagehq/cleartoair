// The release signing key: one ECDSA P-256 key pair whose private half signs every
// dist/latest.json (tools/package.mjs) and whose public half is compiled into every
// build - the agent (agent/src/release-key.js) and the tray launcher
// (tools/launcher/ReleaseKey.cs). An installed copy refuses any update manifest that
// this key did not sign, so a compromised GitHub org, repo or release cannot ship code.
//
//   node tools/release-key.mjs generate [--key <file>] [--force] [--add]
//       Creates the key pair. The PRIVATE key goes OUTSIDE the repo, by default
//       %USERPROFILE%\.cleartoair\release-signing-key.pem (or %CTA_RELEASE_KEY%).
//       Refuses to replace an existing key unless --force (the old file is kept,
//       renamed). Writes the public key into agent/src/release-key.js and
//       tools/launcher/ReleaseKey.cs; --add keeps the keys already listed there
//       (key rotation, see docs/RELEASE.md "Signing").
//   node tools/release-key.mjs show [--key <file>]
//       Prints the key ids built in, and whether the private key file matches one.
//   node tools/release-key.mjs drop <keyId>
//       Removes a public key from the built-in list (the end of a rotation). Refuses
//       to remove the last one.
//
// Nothing here ever prints or logs the private key.
//
// As a module (tools/package.mjs, agent/src/_selftest.js): signManifest,
// loadPrivateKey, createKeyFile, publicKeyInfo, writePublicFiles, DEFAULT_KEY_PATH.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { manifestPayload, verifyManifest, keyIdOf } from '../agent/src/update.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const AGENT_KEY_FILE = path.join(ROOT, 'agent', 'src', 'release-key.js');
export const LAUNCHER_KEY_FILE = path.join(ROOT, 'tools', 'launcher', 'ReleaseKey.cs');
export const DEFAULT_KEY_PATH = process.env.CTA_RELEASE_KEY || path.join(os.homedir(), '.cleartoair', 'release-signing-key.pem');

/** { keyId, spki (PEM), x, y (hex, 32 bytes each) } for a public or private key. */
export function publicKeyInfo(key) {
  const pub = key instanceof crypto.KeyObject && key.type === 'public' ? key : crypto.createPublicKey(key);
  const jwk = pub.export({ format: 'jwk' });
  if (jwk.kty !== 'EC' || jwk.crv !== 'P-256') throw new Error('the release key must be an EC P-256 key');
  const hex = (b64u) => Buffer.from(b64u, 'base64url').toString('hex').padStart(64, '0');
  return { keyId: keyIdOf(pub), spki: pub.export({ type: 'spki', format: 'pem' }), x: hex(jwk.x), y: hex(jwk.y) };
}

export function loadPrivateKey(file = DEFAULT_KEY_PATH) {
  const key = crypto.createPrivateKey(fs.readFileSync(file));
  if (key.asymmetricKeyType !== 'ec' || key.asymmetricKeyDetails?.namedCurve !== 'prime256v1') throw new Error(`${file} is not an EC P-256 private key`);
  return key;
}

/**
 * New key pair; the private half is written to `file` (directory created). Refuses an
 * existing file unless force, and even then keeps it, renamed, rather than losing it.
 * Returns the public info only.
 */
export function createKeyFile(file = DEFAULT_KEY_PATH, { force = false } = {}) {
  if (fs.existsSync(file)) {
    if (!force) throw new Error(`a release key already exists at ${file} - refusing to replace it (pass --force to rotate; the old file is kept, renamed)`);
    const kept = `${file}.replaced-${new Date().toISOString().replace(/[:.]/g, '-')}`;
    fs.renameSync(file, kept);
    console.log(`  kept the previous key as ${kept}`);
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const { privateKey, publicKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'P-256' });
  fs.writeFileSync(file, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600, flag: 'wx' });
  return publicKeyInfo(publicKey);
}

/** The manifest plus { keyId, sig }. Throws if a signed field is malformed. */
export function signManifest(manifest, privateKey) {
  const key = privateKey instanceof crypto.KeyObject ? privateKey : crypto.createPrivateKey(privateKey);
  const sig = crypto.sign('sha256', manifestPayload(manifest), { key, dsaEncoding: 'ieee-p1363' }).toString('base64');
  const signed = { ...manifest, keyId: publicKeyInfo(key).keyId, sig };
  const back = verifyManifest(signed, [publicKeyInfo(key)]);
  if (!back.ok) throw new Error(`the manifest did not verify right after signing: ${back.error}`);
  return signed;
}

export function renderAgentKeys(keys) {
  return `// GENERATED by tools/release-key.mjs - do not edit by hand.
//
// The PUBLIC half of the release signing key(s). agent/src/update.js refuses any
// update manifest not signed by one of these; tools/launcher/ReleaseKey.cs carries the
// same keys for the launcher's own check. The private key never enters this repo.
// More than one entry only during a key rotation (docs/RELEASE.md "Signing").

export const RELEASE_KEYS = ${JSON.stringify(keys.map(({ keyId, x, y, spki }) => ({ keyId, x, y, spki })), null, 2)};

export default RELEASE_KEYS;
`;
}

export function renderLauncherKeys(keys) {
  const rows = keys.map((k) => `            // keyId ${k.keyId}\n            new string[] { "${k.x}", "${k.y}" },`).join('\n');
  return `// GENERATED by tools/release-key.mjs - do not edit by hand.
//
// The PUBLIC half of the release signing key(s), as the raw P-256 point (X, Y; 32
// bytes each, hex) that CngKey.Import wants. ManifestCheck in ClearToAir.cs refuses
// any update not signed by one of these. Same keys as agent/src/release-key.js.

namespace ClearToAir
{
    static class ReleaseKey
    {
        public static readonly string[][] Keys = new string[][]
        {
${rows}
        };
    }
}
`;
}

export function writePublicFiles(keys) {
  fs.writeFileSync(AGENT_KEY_FILE, renderAgentKeys(keys));
  fs.writeFileSync(LAUNCHER_KEY_FILE, renderLauncherKeys(keys));
}

async function builtInKeys() {
  try { return (await import(pathToFileURL(AGENT_KEY_FILE).href + `?t=${Date.now()}`)).RELEASE_KEYS || []; }
  catch { return []; }
}

async function main(argv) {
  const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
  const file = path.resolve(opt('--key') || DEFAULT_KEY_PATH);
  const cmd = argv[0];
  if (cmd === 'generate') {
    const inside = path.relative(ROOT, file);
    if (!inside.startsWith('..') && !path.isAbsolute(inside)) throw new Error(`refusing to put the private key inside the repo (${file})`);
    const info = createKeyFile(file, { force: argv.includes('--force') });
    const keep = argv.includes('--add') ? (await builtInKeys()).filter((k) => k.keyId !== info.keyId) : [];
    writePublicFiles([info, ...keep]);
    console.log(`
  release signing key created
    private key  ${file}
    keyId        ${info.keyId}
    public key   agent/src/release-key.js + tools/launcher/ReleaseKey.cs${keep.length ? ` (plus ${keep.length} kept: ${keep.map((k) => k.keyId).join(', ')})` : ''}

  !! BACK UP THE PRIVATE KEY NOW - an offline copy (USB stick in a drawer) and your
  !! password manager. If it is lost, no installed copy can ever be updated again:
  !! every user would have to download a new build by hand. If it leaks, anyone can
  !! sign an update - rotate (docs/RELEASE.md "Signing"). Never commit it.

  Rebuild the launcher (tools\\launcher\\build.cmd) and commit the two public files.
`);
    return;
  }
  if (cmd === 'show') {
    const keys = await builtInKeys();
    console.log(keys.length ? 'built in:' : 'built in: none (run: node tools/release-key.mjs generate)');
    for (const k of keys) console.log(`  keyId ${k.keyId}  sha256(spki) ${crypto.createHash('sha256').update(crypto.createPublicKey(k.spki).export({ type: 'spki', format: 'der' })).digest('hex')}`);
    if (fs.existsSync(file)) {
      const id = publicKeyInfo(loadPrivateKey(file)).keyId;
      console.log(`private key ${file}: keyId ${id} - ${keys.some((k) => k.keyId === id) ? 'matches a built-in key' : 'NOT built in; manifests it signs will be refused'}`);
    } else console.log(`private key ${file}: not found`);
    return;
  }
  if (cmd === 'drop') {
    const id = String(argv[1] || '').toLowerCase();
    const keys = await builtInKeys();
    if (!keys.some((k) => k.keyId === id)) throw new Error(`no built-in key ${id || '(none given)'}; built in: ${keys.map((k) => k.keyId).join(', ') || 'none'}`);
    if (keys.length === 1) throw new Error('refusing to drop the only release key - installed copies could never be updated again');
    writePublicFiles(keys.filter((k) => k.keyId !== id));
    console.log(`dropped ${id}; rebuild the launcher (tools\\launcher\\build.cmd) and release.`);
    return;
  }
  console.log('usage: node tools/release-key.mjs generate [--key <file>] [--force] [--add]\n       node tools/release-key.mjs show [--key <file>]\n       node tools/release-key.mjs drop <keyId>');
  process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((e) => { console.error(`release-key: ${e.message}`); process.exit(1); });
}
